export function newsText(item) {
    return typeof item.text === 'function' ? item.text() : item.text
}

export function pickNewsMessage() {
    const eligible = newsMessages.filter((item) => !item.condition || item.condition())
    return eligible[Math.floor(Math.random() * eligible.length)] ?? null
}
